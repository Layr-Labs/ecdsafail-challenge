fn input_hash(ops: &[Op]) -> String {
    let mut h = Sha3_256::new();
    for o in ops {
        h.update((o.kind as u32).to_le_bytes());
        h.update([0u8; 4]);
        for v in [
            o.q_control2.0,
            o.q_control1.0,
            o.q_target.0,
            o.c_target.0,
            o.c_condition.0,
            o.r_target.0,
        ] {
            h.update(v.to_le_bytes());
        }
    }
    format!("{:x}", h.finalize())
}

fn cx(q: u64, t: u64) -> Op {
    let mut o = Op::empty();
    o.kind = K::CX;
    o.q_control1 = QubitId(q);
    o.q_target = QubitId(t);
    o
}

fn hmr(q: u64) -> Op {
    let mut o = Op::empty();
    o.kind = K::Hmr;
    o.q_target = QubitId(q);
    o.c_target = BitId(SCRATCH_CT);
    o
}

fn cz_cond(c1: u64, c2: u64) -> Op {
    let mut o = Op::empty();
    o.kind = K::CZ;
    o.q_control1 = QubitId(c1);
    o.q_target = QubitId(c2);
    o.c_condition = BitId(SCRATCH_CT);
    o
}

pub(super) fn run(ops: Vec<Op>) -> Vec<Op> {
    assert_eq!(ops.len(), INPUT_COUNT, "retained_703 input count");
    assert_eq!(input_hash(&ops), INPUT_SHA3, "retained_703 input hash");
    let mut start_map = std::collections::HashMap::with_capacity(LEASES.len());
    let mut end_map = std::collections::HashMap::with_capacity(LEASES.len());
    for (idx, s) in LEASES.iter().enumerate() {
        assert!(start_map.insert(s[0] as usize, idx).is_none());
        assert!(end_map.insert(s[1] as usize, idx).is_none());
    }
    let mut out = Vec::with_capacity(ops.len() + LEASES.len() * 3);
    let mut starts_seen = 0usize;
    let mut ends_seen = 0usize;
    for (i, o) in ops.into_iter().enumerate() {
        if let Some(&idx) = start_map.get(&i) {
            let s = LEASES[idx];
            assert!(
                o.kind == K::CCX
                    && o.q_control2.0 == s[3]
                    && o.q_control1.0 == s[4]
                    && o.q_target.0 == s[5],
                "retained_703 start mismatch at {}",
                i
            );
            let mut fill = o;
            fill.q_target = QubitId(s[2]);
            out.push(fill);
            out.push(cx(s[2], s[5]));
            starts_seen += 1;
        } else if let Some(&idx) = end_map.get(&i) {
            let s = LEASES[idx];
            assert!(
                o.kind == K::CCX
                    && o.q_control2.0 == s[6]
                    && o.q_control1.0 == s[7]
                    && o.q_target.0 == s[8],
                "retained_703 end mismatch at {}",
                i
            );
            out.push(cx(s[2], s[8]));
            out.push(hmr(s[2]));
            out.push(cz_cond(s[6], s[7]));
            ends_seen += 1;
        } else {
            out.push(o);
        }
    }
    assert_eq!(starts_seen, LEASES.len(), "retained_703 starts count");
    assert_eq!(ends_seen, LEASES.len(), "retained_703 ends count");
    out
}

