// END Q62 TABLES
fn q62_on() -> bool {
    static V: OnceLock<bool> = OnceLock::new();
    *V.get_or_init(|| std::env::var("Q62").is_ok_and(|v| v == "1"))
}
/// Block-start range "lo-hi" (inclusive) of the divide (Q62_DIV) or the multiply (Q62_MUL).
fn q62_range(mul: bool) -> (usize, usize) {
    static D: OnceLock<(usize, usize)> = OnceLock::new();
    static M: OnceLock<(usize, usize)> = OnceLock::new();
    let (cell, key, dflt) = if mul { (&M, "Q62_MUL", "42-108") } else { (&D, "Q62_DIV", "0-108") };
    *cell.get_or_init(|| {
        let v = std::env::var(key).unwrap_or_else(|_| dflt.to_string());
        let (a, b) = v.split_once('-').expect("q62 range lo-hi");
        let (lo, hi): (usize, usize) = (a.trim().parse().unwrap(), b.trim().parse().unwrap());
        assert!(lo % 6 == 0 && hi % 6 == 0 && lo <= hi, "q62: block starts must be multiples of 6");
        // every tick of a coded block is an A tick (block 0's tick 0 excepted) and runs in a fused or rails-only pass
        assert!(hi + 5 + 1 < rounds() && a2_tick(hi + 5), "q62: the region must end before the last A tick");
        assert!(hi + 5 < n2_from(mul), "q62: the region must end before the N2 batch");
        assert!(lo >= lf_reorder(mul) || (lo == 0 && !mul && lf_reorder(false) <= 2), "q62: the region must avoid the payload-only ticks");
        (lo, hi)
    })
}
thread_local! {
    static Q62_WALK: std::cell::Cell<Option<bool>> = const { std::cell::Cell::new(None) };
    static Q62_STAGE: std::cell::RefCell<std::collections::HashMap<usize, u8>> = std::cell::RefCell::new(std::collections::HashMap::new());
    static Q62_COINS: std::cell::RefCell<std::collections::HashMap<(usize, u8), crate::circuit::BitId>> = std::cell::RefCell::new(std::collections::HashMap::new());
}
/// Called at the start of each walk (the divide: false, the multiply: true). No op.
pub(super) fn a2_q62_walk(mul: bool) {
    if !q62_on() { return; }
    assert!(Q62_STAGE.with(|m| m.borrow().is_empty()) && Q62_COINS.with(|m| m.borrow().is_empty()), "q62: blocks left open by the previous walk");
    Q62_WALK.with(|w| w.set(Some(mul)));
}
fn q62_block(t: usize) -> bool {
    if !q62_on() { return false; }
    let mul = Q62_WALK.with(|w| w.get()).expect("q62: walk not set");
    let (lo, hi) = q62_range(mul);
    let s = 6 * (t / 6);
    lo <= s && s <= hi
}
fn q62_slot(w: &[Option<QubitId>; 15], i: u8) -> QubitId { w[i as usize].unwrap_or_else(|| panic!("q62: slot {i} empty")) }
fn q62_load(s: usize) -> [Option<QubitId>; 15] {
    let mut w = [None; 15];
    for i in 0..6 {
        w[i] = A2_REC.with(|r| r.borrow().get(&(s + i)).and_then(|f| f[0]));
        w[6 + i] = a2_cell(s + i);
    }
    w
}
fn q62_store(s: usize, w: &[Option<QubitId>; 15]) {
    for i in 0..6 {
        A2_REC.with(|r| match r.borrow_mut().get_mut(&(s + i)) {
            Some(f) => f[0] = w[i],
            None => assert!(w[i].is_none(), "q62: a field without its record entry"),
        });
        assert_eq!(w[6 + i], a2_cell(s + i), "q62: a cell slot changed wire");
    }
    assert!(w[12..].iter().all(|x| x.is_none()), "q62: a temporary left live");
}
fn q62_run(c: &mut Builder, s: usize, ops: &[Q62Op], w: &mut [Option<QubitId>; 15]) {
    for op in ops {
        match *op {
            Q62Op::Cx(a, b) => { c.cx(q62_slot(w, a), q62_slot(w, b)); }
            Q62Op::Ccx(a, b, t) => { c.ccx(q62_slot(w, a), q62_slot(w, b), q62_slot(w, t)); }
            Q62Op::Swp(k, a, b) => { a2_pair_swap(c, q62_slot(w, k), q62_slot(w, a), q62_slot(w, b)); }
            Q62Op::And(a, b, t) => {
                assert!(w[t as usize].is_none(), "q62: AND into a live slot");
                let r = and_new(c, q62_slot(w, a), q62_slot(w, b));
                w[t as usize] = Some(r);
            }
            Q62Op::Hmr(t, k) => {
                let q = q62_slot(w, t);
                let m = c.alloc_bit();
                c.hmr(q, m);
                c.release_clean(q);
                w[t as usize] = None;
                assert!(Q62_COINS.with(|x| x.borrow_mut().insert((s, k), m)).is_none(), "q62: coin taken twice");
            }
            Q62Op::Rest(t, k) => {
                let m = Q62_COINS.with(|x| x.borrow_mut().remove(&(s, k))).expect("q62: coin missing");
                c.z_if(q62_slot(w, t), m);
                c.free_bit(m);
            }
            Q62Op::Erz(t, a, b) => {
                and_erase(c, q62_slot(w, t), q62_slot(w, a), q62_slot(w, b));
                w[t as usize] = None;
            }
            Q62Op::Mov(a, b) => {
                assert!(w[b as usize].is_none(), "q62: move into a live slot");
                w[b as usize] = w[a as usize].take();
            }
        }
    }
}
fn q62_stage(s: usize, from: u8, to: u8) {
    Q62_STAGE.with(|m| {
        let mut m = m.borrow_mut();
        let cur = m.get(&s).copied().unwrap_or(0);
        assert_eq!(cur, from, "q62: block {s} out of order");
        if to == 0 { m.remove(&s); } else { m.insert(s, to); }
    });
}
/// Whether tick t's letter is raw (its field and cell hold f and b) at the block's current stage.
fn q62_raw(t: usize) -> bool {
    let (s, i) = (6 * (t / 6), t % 6);
    let st = Q62_STAGE.with(|m| m.borrow().get(&s).copied().unwrap_or(0));
    if s == 0 {
        match i { 1 | 3 | 5 => st < 4, 2 | 4 => st < 3, _ => true }
    } else {
        match i { 0 | 1 => st < 1, 2 => st < 2, 4 => st < 3, _ => st < 4 }
    }
}
/// End of forward tick t (every A tick calls it, as a2_pair_commit).
fn q62_commit(c: &mut Builder, t: usize, k3: QubitId) {
    assert!(a2_emax(t) <= 5, "q62 record requires emax<=5");
    assert_eq!(a2_field(t)[0], Some(k3), "q62: the decision must write its dense field slot");
    let (s, i) = (6 * (t / 6), t % 6);
    let (ops, from, to, pk): (&[Q62Op], u8, u8, Option<usize>) = match (s == 0, i) {
        (false, 1) => (Q62_A, 0, 1, Some(s)),
        (false, 2) => (Q62_ABS, 1, 2, None),
        (false, 4) => (Q62_B, 2, 3, Some(s + 2)),
        (false, 5) => (Q62_C, 3, 4, Some(s + 3)),
        (true, 4) => (Q62_B, 0, 3, Some(2)),
        (true, 5) => (Q62_C0, 3, 4, Some(3)),
        _ => return,
    };
    q62_stage(s, from, to);
    let mut w = q62_load(s);
    q62_run(c, s, ops, &mut w);
    q62_store(s, &w);
    if let Some(p) = pk { assert!(A2_PAIR_PACKED.with(|v| v.borrow_mut().insert(p)), "q62: pair committed twice"); }
}
/// Start of reverse tick t: the pop due at this tick, then tick t's raw flag leaves (as a2_pair_consume).
fn q62_consume(c: &mut Builder, t: usize) -> QubitId {
    let (s, i) = (6 * (t / 6), t % 6);
    let pop: Option<(&[Q62Op], u8, u8, Option<usize>)> = match (s == 0, i) {
        (false, 5) => Some((Q62_PC, 4, 3, Some(s + 3))),
        (false, 4) => Some((Q62_PB, 3, 2, Some(s + 2))),
        (false, 2) => Some((Q62_PABS, 2, 1, None)),
        (false, 1) => Some((Q62_PA, 1, 0, Some(s))),
        (true, 5) => Some((Q62_PC0, 4, 3, Some(3))),
        (true, 4) => Some((Q62_PB, 3, 0, Some(2))),
        _ => None,
    };
    if let Some((ops, from, to, pk)) = pop {
        q62_stage(s, from, to);
        if let Some(p) = pk { assert!(A2_PAIR_PACKED.with(|v| v.borrow_mut().remove(&p)), "q62: pair is not packed"); }
        let mut w = q62_load(s);
        q62_run(c, s, ops, &mut w);
        q62_store(s, &w);
    }
    assert!(q62_raw(t), "q62: tick {t} consumed while coded");
    let f = A2_REC.with(|v| v.borrow_mut().remove(&t)).expect("q62 consumed field");
    assert!(f[1].is_none());
    A2_CELLS.with(|v| { v.borrow_mut().remove(&t); });
    f[0].expect("q62: raw flag absent")
}
/// Non-consuming read of a raw letter (the same ops as the pair code's raw read).
fn q62_read(c: &mut Builder, t: usize) -> (QubitId, QubitId) {
    assert!(q62_raw(t), "q62: non-consuming read of coded tick {t}");
    let f = a2_field(t)[0].expect("q62 raw read flag");
    let b = a2_cell(t).expect("q62 raw read k2");
    let q = c.alloc_qubit(); let u = c.alloc_qubit(); c.cx(f, q); c.cx(b, u);
    (q, u)
}
fn q62_read_erase(c: &mut Builder, t: usize, q: QubitId, u: QubitId) {
    assert!(q62_raw(t), "q62: read erase of coded tick {t}");
    let f = a2_field(t)[0].expect("q62 raw erase flag");
    let b = a2_cell(t).expect("q62 raw erase k2");
    c.cx(b, u); c.cx(f, q); c.release_clean(u); c.release_clean(q);
}
fn q62_lin(s: usize, slots: &[u8]) -> Lin {
    let ws: Vec<QubitId> = slots.iter().map(|&i| A2_REC.with(|r| r.borrow().get(&(s + i as usize)).and_then(|f| f[0])).expect("q62 spent wire")).collect();
    Lin::of(&ws)
}
fn q62_sp_row(t: usize) -> (&'static [u8], &'static [u8], &'static [u8]) {
    let (s, i) = (6 * (t / 6), t % 6);
    if s == 0 { Q62_SP_B0[i] } else { Q62_SP_REG[i] }
}
/// The affine part L0 of spent(t) (a2_spent's form).
fn q62_spent(t: usize) -> Lin {
    let (_, _, l0) = q62_sp_row(t);
    q62_lin(6 * (t / 6), l0)
}
/// The product part (L1, L2) of spent(t), or None; yp8_logic_a ANDs it onto a wire around the decision.
fn q62_sp(t: usize) -> Option<(Lin, Lin)> {
    if !q62_block(t) { return None; }
    let (l1, l2, _) = q62_sp_row(t);
    if l1.is_empty() { return None; }
    let s = 6 * (t / 6);
    Some((q62_lin(s, l1), q62_lin(s, l2)))
}
/// Decision reserve in pair mode: the g wire where spent is not constant, plus the product wire.
fn q62_reserve(t: usize) -> usize {
    let (l1, _, l0) = q62_sp_row(t);
    usize::from(!l1.is_empty() || !l0.is_empty()) + usize::from(!l1.is_empty())
}
/// Q62_PK: the walks that keep the r1227 record pack when Q62=1 ("div,mul", the default, "div", "mul" or "none").
/// The pack restores a wrong record when its 41 flags have weight >= 21; the (6,2) escape sets all three flags of a
/// block, so the pack's failure rate rises (walk model: about 0.03 -> 0.8 per packet). Q62 unset: never skips.
fn q62_pk_skip() -> bool {
    if !q62_on() { return false; }
    static V: OnceLock<String> = OnceLock::new();
    let keep = V.get_or_init(|| std::env::var("Q62_PK").unwrap_or_else(|_| "div,mul".to_string()));
    let mul = Q62_WALK.with(|w| w.get()).expect("q62: walk not set");
    !keep.split(',').any(|k| k.trim() == if mul { "mul" } else { "div" })
}
