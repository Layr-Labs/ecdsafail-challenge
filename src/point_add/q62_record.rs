// ---------------------------------------------------------------------------------------------------------------------
// q62 (round 116, lane A8 q62build) + s16 (lane A16 codec2): the exact (6,2) record code on K223's matching
// (0,1),(2,4),(3,5), at most two e >= 4 letters per 6-tick block, plus a third at block tick 5 when pair A or pair B
// is double (s16: the 16 codes (6,2) leaves unused), in place of the pair code on the divide's blocks Q62_DIV and the multiply's blocks
// Q62_MUL (block starts, defaults 0-108 and 42-108; K223 everywhere else, block by block).
// - LIFO: pushes at the ends of block ticks 1, 2, 4, 5 (block 0: 4, 5); pops at the starts of reverse block ticks
//   5, 4, 2, 1 (block 0: 5, 4). Residuals gA (over tick 2) and gB (over tick 5) are the code's only transients.
// - Every erased residual is X-measured; its coin is kept and repaid (Z on the recomputed wire) by the matching pop.
// - spent(t) = L1 * L2 + L0 over record fields (one AND for the product, in yp8_logic_a).
// - Letters are read non-consuming only while raw (asserted): the regions avoid every payload-only pass.
// - Q62 unset: every hook returns before emitting an op or allocating a wire (the stream is byte-identical).
// Tables are generated by codec2/s16gen.py and replayed on every legal block by codec2/s16check.py.
// ---------------------------------------------------------------------------------------------------------------------
#[derive(Clone, Copy, Debug)]
enum Q62Op { Cx(u8, u8), Ccx(u8, u8, u8), Swp(u8, u8, u8), And(u8, u8, u8), Hmr(u8, u8), Rest(u8, u8), Erz(u8, u8, u8), Mov(u8, u8) }
// slots: 0..5 field (k3) of block tick 0..5, 6..11 its cell (k2), 12 dA, 13 t1/h, 14 G; coins 0 gA, 1 dA, 2 dB/gB, 3 gC, 4 h
// BEGIN Q62 TABLES (generated by q62gen.py; q62check.py parses this block)
