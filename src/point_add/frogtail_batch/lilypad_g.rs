/// In-place low-page codec
///
///     U -> V = (G U + (-1)^rho p) F^-1 mod 2^r.
///
/// `G`, `F`, and `U` are little-endian r-bit two's-complement views with G/F
/// odd.  The caller supplies a physical |1>, restored clean carry lanes, and
/// arbitrary restored dirty loans.  Recording this body and playing it in
/// reverse gives V -> U with the same sources.
pub(super) fn page_codec_u_to_v(
    b: &mut B,
    u: &[QubitId],
    g: &[QubitId],
    f: &[QubitId],
    rho: QubitId,
    one: QubitId,
    dirty: &[QubitId],
) {
    let r = u.len();
    assert!(r >= 3 && r <= 16);
    assert_eq!(g.len(), r);
    assert_eq!(f.len(), r);
    assert!(dirty.len() >= r.saturating_sub(2).max(4));

    // Multiply by the odd G.
    super::lilypad::finish_mul_no_tmp(b, &g[1..], u, one, dirty);

    // (-1)^rho p = p + rho*(-2p) modulo 2^r.
    let mask = (1u64 << r) - 1;
    let p = super::frogdrop_sched::p().as_limbs()[0] & mask;
    let add_constant = |b: &mut B, ctl: QubitId, k: u64| {
        for j in 0..r {
            if k & (1 << j) == 0 { continue; }
            let word = &u[j..];
            for i in (1..word.len()).rev() {
                let mut controls = vec![(ctl, false)];
                controls.extend(word[..i].iter().copied().map(|q| (q, false)));
                super::mask::mc_xor(b, &controls, word[i], &[], dirty);
            }
            b.cx(ctl, word[0]);
        }
    };
    add_constant(b, one, p);
    add_constant(b, rho, (!p.wrapping_mul(2)).wrapping_add(1) & mask);

    // Divide by odd F by reversing the exact in-place multiplier.
    b.begin();
    super::lilypad::finish_mul_no_tmp(b, &f[1..], u, one, dirty);
    let mul_f = b.end();
    b.play(&mul_f, true);
}

/// XOR the determinant page V into arbitrary-state hosts while restoring U.
/// This is the page oracle needed when the only available carriers already
/// contain the inverse Q word.
pub(super) fn page_codec_xor_v(
    b: &mut B,
    out: &[QubitId],
    u: &[QubitId],
    g: &[QubitId],
    f: &[QubitId],
    rho: QubitId,
    one: QubitId,
    dirty: &[QubitId],
) {
    assert_eq!(out.len(), u.len());
    b.begin();
    page_codec_u_to_v(b, u, g, f, rho, one, dirty);
    let codec = b.end();
    b.play(&codec, false);
    for (&v, &target) in u.iter().zip(out) { b.cx(v, target); }
    b.play(&codec, true);
}

/// Q852 page: below Q853 the inverse walk pages a fourth low cofactor lane, V3 = bsig(3), with V0..V2. Every
/// tick boundary satisfies G U - F V = -(-1)^rho p (mod 2^r) on the stored lanes, so V mod 16 =
/// (G U + (-1)^rho p) F^-1 mod 16 is a function of the low lanes of G, F, U and rho. V0 = U0 ^ 1 when G and F
/// are odd, so it needs no host: the three page hosts of each window carry V1..V3.
pub(super) const LQ_PAGE4: bool = super::pointadd_lilypad::PEAK0 <= 852;
/// Q851 page: V4 = bsig(4) is paged as well (V mod 32 from the low five lanes of G, F, U and rho).
pub(super) const LQ_PAGE5: bool = super::pointadd_lilypad::PEAK0 <= 851;
/// Q850 page: V5 = bsig(5) as well (V mod 64).
pub(super) const LQ_PAGE6: bool = super::pointadd_lilypad::PEAK0 <= 850;
/// Paged low lanes of V in the inverse walk.
pub(super) const PAGE_INV: usize = if LQ_PAGE6 { 6 } else if LQ_PAGE5 { 5 } else if LQ_PAGE4 { 4 } else { PAGE3_R };

/// Literal of a page-formula input: a constant or a lane.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(super) enum PL {
    C(bool),
    Q(QubitId),
}

/// ANF (monomial masks over the distinct lanes of `shape`) of bit `bit` of V = (G U + sp) F^-1 mod 16, where the
/// 13 slots are g0..g3, f0..f3, u0..u3, rho: -1 = constant 0, -2 = constant 1, k >= 0 = distinct lane k; sp = p
/// mod 16 for rho = 0 and -p mod 16 for rho = 1.
fn lq_anf(bit: usize, shape: &[i16; 13]) -> std::rc::Rc<Vec<u32>> {
    thread_local! {
        static CACHE: std::cell::RefCell<std::collections::HashMap<(usize, [i16; 13]), std::rc::Rc<Vec<u32>>>> =
            std::cell::RefCell::new(std::collections::HashMap::new());
    }
    if let Some(v) = CACHE.with(|c| c.borrow().get(&(bit, *shape)).cloned()) {
        return v;
    }
    let nv = shape.iter().filter(|&&s| s >= 0).map(|&s| s as usize + 1).max().unwrap_or(0);
    assert!(nv <= 16);
    assert_eq!(shape[4], -2, "F must be odd: f0 is the constant 1");
    let p16 = (super::frogdrop_sched::p().as_limbs()[0] & 15) as usize;
    let mut tt = vec![0u8; 1 << nv];
    for a in 0..1usize << nv {
        let v = |k: usize| -> usize {
            match shape[k] {
                -1 => 0,
                -2 => 1,
                s => (a >> s) & 1,
            }
        };
        let word = |o: usize| (0..4).map(|i| v(o + i) << i).sum::<usize>();
        let (g, f, u, rho) = (word(0), word(4), word(8), v(12));
        let sp = if rho == 0 { p16 } else { (16 - p16) & 15 };
        let inv = (1..16).step_by(2).find(|z| (f * z) & 15 == 1).unwrap();
        tt[a] = ((((g * u + sp) * inv) & 15) >> bit & 1) as u8;
    }
    for k in 0..nv {
        for m in 0..1usize << nv {
            if m & (1 << k) != 0 {
                tt[m] ^= tt[m ^ (1 << k)];
            }
        }
    }
    let r = std::rc::Rc::new((0..1usize << nv).filter(|&m| tt[m] != 0).map(|m| m as u32).collect::<Vec<_>>());
    CACHE.with(|c| c.borrow_mut().insert((bit, *shape), r.clone()));
    r
}

/// target ^= [ctl] & bit `bit` of V = (G U + sp) F^-1 mod 16 (literals of the low four lanes of G, F, U and of
/// rho), by its ANF with the codebase's dirty multi-controlled toggles; `dirty` lanes are borrowed and restored.
#[allow(clippy::too_many_arguments)]
pub(super) fn lq_v_xor(
    b: &mut B,
    bit: usize,
    g: [PL; 4],
    f: [PL; 4],
    u: [PL; 4],
    rho: PL,
    ctl: Option<QubitId>,
    target: QubitId,
    dirty: &[QubitId],
) {
    let slots: Vec<PL> = g.iter().chain(&f).chain(&u).copied().chain([rho]).collect();
    let mut lanes: Vec<QubitId> = vec![];
    let mut shape = [0i16; 13];
    for (k, l) in slots.iter().enumerate() {
        shape[k] = match *l {
            PL::C(false) => -1,
            PL::C(true) => -2,
            PL::Q(q) => {
                let i = lanes.iter().position(|&x| x == q).unwrap_or_else(|| {
                    lanes.push(q);
                    lanes.len() - 1
                });
                i as i16
            }
        };
    }
    assert!(!lanes.contains(&target) && ctl.map_or(true, |c| c != target && !lanes.contains(&c)));
    let dirty: Vec<QubitId> =
        dirty.iter().copied().filter(|q| *q != target && !lanes.contains(q) && Some(*q) != ctl).collect();
    for &m in lq_anf(bit, &shape).iter() {
        let mut controls: Vec<(QubitId, bool)> = ctl.into_iter().map(|c| (c, false)).collect();
        controls.extend((0..lanes.len()).filter(|k| m & (1 << k) != 0).map(|k| (lanes[k], false)));
        super::mask::mc_xor(b, &controls, target, &[], &dirty);
    }
}

/// Fold a parity into its first lane (CNOTs, and X for the flip); returns its literal. Undo with lq_unfold.
pub(super) fn lq_fold(b: &mut B, p: &ParityCtl) -> PL {
    if p.qs.is_empty() {
        return PL::C(p.flip);
    }
    for &q in &p.qs[1..] {
        b.cx(q, p.qs[0]);
    }
    if p.flip {
        b.x(p.qs[0]);
    }
    PL::Q(p.qs[0])
}

pub(super) fn lq_unfold(b: &mut B, p: &ParityCtl) {
    if p.qs.is_empty() {
        return;
    }
    if p.flip {
        b.x(p.qs[0]);
    }
    for &q in p.qs[1..].iter().rev() {
        b.cx(q, p.qs[0]);
    }
}

/// Low-lane literals of the value rings in frame `frame`: lanes 1..3 of G and F (lane 0 is the constant `l0`).
/// At frames with kv = 3 the stored values are three-lane signed numbers, so lane 3 is the sign extension of lane 2.
fn lq_value_lits(w: &PWalk, sch: &PSched, frame: usize, g0: bool) -> ([PL; 4], [PL; 4]) {
    let kv = sch.kv[frame];
    assert!(kv >= 3 && sch.c[frame] >= 3);
    let l3 = if kv >= 4 { 3 } else { 2 };
    (
        [PL::C(g0), PL::Q(w.af(frame, 1)), PL::Q(w.af(frame, 2)), PL::Q(w.af(frame, l3))],
        [PL::C(true), PL::Q(w.bf(1)), PL::Q(w.bf(2)), PL::Q(w.bf(l3))],
    )
}

/// U literals of frame `frame` (lanes asig 0..3; lane 0 the constant 0 when sigma is hosted there).
fn lq_u_lits(w: &PWalk, frame: usize, u0_hosted: bool) -> [PL; 4] {
    [
        if u0_hosted { PL::C(false) } else { PL::Q(w.asig(frame, 0)) },
        PL::Q(w.asig(frame, 1)),
        PL::Q(w.asig(frame, 2)),
        PL::Q(w.asig(frame, 3)),
    ]
}

/// XOR V1..V3 of frame `frame` into `hosts` (G0 the constant `g0`, F0 = 1).
#[allow(clippy::too_many_arguments)]
fn lq_page_xor(
    b: &mut B,
    w: &PWalk,
    sch: &PSched,
    frame: usize,
    g0: bool,
    u0_hosted: bool,
    rho: &ParityCtl,
    hosts: &[QubitId],
    dirty: &[QubitId],
) {
    assert_eq!(hosts.len(), 3);
    let (g, f) = lq_value_lits(w, sch, frame, g0);
    let u = lq_u_lits(w, frame, u0_hosted);
    let r = lq_fold(b, rho);
    for bit in 1..4 {
        lq_v_xor(b, bit, g, f, u, r, None, hosts[bit - 1], dirty);
    }
    lq_unfold(b, rho);
}

/// XOR V3 (and the parity `conj`) of frame `frame` (G0 = F0 = 1) into `target`.
#[allow(clippy::too_many_arguments)]
pub(super) fn lq_v3_xor(
    b: &mut B,
    w: &PWalk,
    sch: &PSched,
    frame: usize,
    u0_hosted: bool,
    rho: &ParityCtl,
    conj: Option<&ParityCtl>,
    target: QubitId,
    dirty: &[QubitId],
) {
    let (g, f) = lq_value_lits(w, sch, frame, true);
    let u = lq_u_lits(w, frame, u0_hosted);
    let r = lq_fold(b, rho);
    lq_v_xor(b, 3, g, f, u, r, None, target, dirty);
    lq_unfold(b, rho);
    if let Some(c) = conj {
        c.xor_into(b, target);
    }
}

/// t[1..] += a[1..] + c1 (mod 2^n), a restored, where the target's lane 0 is virtual and its carry c1 = a0 & s,
/// s = XOR(s_lanes) ^ s_inv: the flipped target bit 0 is V0 ^ s = U0 ^ 1 ^ s, and (U0 ^ 1 ^ s) U0 = s U0. The
/// gates are ttk_add_hooked's with its two lane-0 carry Toffolis replaced by that carry and the lane-0 write
/// dropped; the hooks are its carry hooks.
fn ttk_add_hooked_t0s(b: &mut B, a: &[QubitId], t1: &[QubitId], s_lanes: &[QubitId], s_inv: bool, hooks: &[(usize, BitId)]) {
    let n = t1.len() + 1;
    assert_eq!(a.len(), n);
    assert!(n >= 3 && !s_lanes.is_empty());
    let t = |i: usize| t1[i - 1];
    let c1 = |b: &mut B| {
        for &q in &s_lanes[1..] {
            b.cx(q, s_lanes[0]);
        }
        b.ccx(s_lanes[0], a[0], a[1]);
        if s_inv {
            b.cx(a[0], a[1]);
        }
        for &q in s_lanes[1..].iter().rev() {
            b.cx(q, s_lanes[0]);
        }
    };
    for &(i, m) in hooks {
        assert!(i >= 1 && i < n, "carry hook {i} outside 1..{n}");
        b.z_if(a[i], m);
    }
    for i in 1..n {
        b.cx(a[i], t(i));
    }
    for i in (1..n - 1).rev() {
        b.cx(a[i], a[i + 1]);
    }
    c1(b);
    for i in 1..n - 1 {
        b.ccx(t(i), a[i], a[i + 1]);
    }
    for &(i, m) in hooks {
        b.z_if(a[i], m);
    }
    for i in (2..n).rev() {
        b.cx(a[i], t(i));
        b.ccx(t(i - 1), a[i - 1], a[i]);
    }
    b.cx(a[1], t(1));
    c1(b);
    for i in 1..n - 1 {
        b.cx(a[i], a[i + 1]);
    }
    for i in 1..n {
        b.cx(a[i], t(i));
    }
}

// ------------------------------------------------------------------------------------------------------------------
// Q851 page: V mod 32. The low five lanes of V are not stored in the inverse walk. Every read is served from the
// identity V = (G U + sp) F^-1 mod 32 (sp = p for rho = 0, -p for rho = 1), by small exact modular arithmetic on
// the low lanes (frames with at least five value lanes) or by the ANF of the exact truth table (the narrow frames).

/// Page width of the Q851 / Q850 inverse walk.
pub(super) const LQ_R: usize = if LQ_PAGE6 { 6 } else { 5 };
/// Below Q851 the step core also hosts in G'1: the digit makes G' = G +- F = 2 (mod 4) on every shot.
pub(super) const LQ_G1_HOST: bool = LQ_R >= 6;

/// What a mod-2^r page formula returns: bit of V, or bit of V ^ U.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub(super) enum LqKind {
    V,
    D,
}

/// V = (G U + sp) F^-1 mod 2^r for odd F.
pub(super) fn lq_ref_v(r: usize, g: u64, f: u64, u: u64, rho: bool) -> u64 {
    let m = (1u64 << r) - 1;
    let p = super::frogdrop_sched::p().as_limbs()[0] & m;
    let sp = if rho { p.wrapping_neg() & m } else { p };
    assert!(f & 1 == 1);
    let mut inv = 1u64;
    for _ in 0..8 {
        inv = inv.wrapping_mul(2u64.wrapping_sub(f.wrapping_mul(inv))) & m;
    }
    assert_eq!(f.wrapping_mul(inv) & m, 1);
    g.wrapping_mul(u).wrapping_add(sp).wrapping_mul(inv) & m
}

/// ANF over the distinct lanes of `shape` (3r + 1 slots g0.., f0.., u0.., rho: -1 = constant 0, -2 = constant 1,
/// k >= 0 = distinct lane k), generated from the exact truth table of every assignment.
fn lq_anf_r(r: usize, kind: LqKind, bit: usize, shape: &[i16]) -> std::rc::Rc<Vec<u32>> {
    type Key = (usize, LqKind, usize, Vec<i16>);
    thread_local! {
        static CACHE: std::cell::RefCell<std::collections::HashMap<Key, std::rc::Rc<Vec<u32>>>> =
            std::cell::RefCell::new(std::collections::HashMap::new());
    }
    let key = (r, kind, bit, shape.to_vec());
    if let Some(v) = CACHE.with(|c| c.borrow().get(&key).cloned()) {
        return v;
    }
    assert_eq!(shape.len(), 3 * r + 1);
    assert_eq!(shape[r], -2, "F must be odd: f0 is the constant 1");
    let nv = shape.iter().filter(|&&s| s >= 0).map(|&s| s as usize + 1).max().unwrap_or(0);
    assert!(nv <= 20);
    let mut tt = vec![0u8; 1 << nv];
    for a in 0..1usize << nv {
        let v = |k: usize| -> u64 {
            match shape[k] {
                -1 => 0,
                -2 => 1,
                s => ((a >> s) & 1) as u64,
            }
        };
        let word = |o: usize| (0..r).map(|i| v(o + i) << i).sum::<u64>();
        let (g, f, u, rho) = (word(0), word(r), word(2 * r), v(3 * r) == 1);
        let mut x = lq_ref_v(r, g, f, u, rho);
        if kind == LqKind::D {
            x ^= u;
        }
        tt[a] = ((x >> bit) & 1) as u8;
    }
    for k in 0..nv {
        for m in 0..1usize << nv {
            if m & (1 << k) != 0 {
                tt[m] ^= tt[m ^ (1 << k)];
            }
        }
    }
    let res = std::rc::Rc::new((0..1usize << nv).filter(|&m| tt[m] != 0).map(|m| m as u32).collect::<Vec<_>>());
    CACHE.with(|c| c.borrow_mut().insert(key, res.clone()));
    res
}

/// target ^= [ctl] & (bit `bit` of the page formula `kind`) from the literals of the low r lanes of G, F, U and of
/// rho, by its ANF with the codebase's dirty multi-controlled toggles (`dirty` borrowed and restored).
#[allow(clippy::too_many_arguments)]
pub(super) fn lq_vr_xor(
    b: &mut B,
    r: usize,
    kind: LqKind,
    bit: usize,
    g: &[PL],
    f: &[PL],
    u: &[PL],
    rho: PL,
    ctl: Option<QubitId>,
    target: QubitId,
    dirty: &[QubitId],
) {
    assert!(g.len() == r && f.len() == r && u.len() == r);
    let slots: Vec<PL> = g.iter().chain(f).chain(u).copied().chain([rho]).collect();
    let mut lanes: Vec<QubitId> = vec![];
    let shape: Vec<i16> = slots
        .iter()
        .map(|l| match *l {
            PL::C(false) => -1,
            PL::C(true) => -2,
            PL::Q(q) => {
                let i = lanes.iter().position(|&x| x == q).unwrap_or_else(|| {
                    lanes.push(q);
                    lanes.len() - 1
                });
                i as i16
            }
        })
        .collect();
    let anf = lq_anf_r(r, kind, bit, &shape);
    assert!(!lanes.contains(&target) && ctl.map_or(true, |c| c != target && !lanes.contains(&c)));
    let dirty: Vec<QubitId> =
        dirty.iter().copied().filter(|q| *q != target && !lanes.contains(q) && Some(*q) != ctl).collect();
    for &m in anf.iter() {
        let mut controls: Vec<(QubitId, bool)> = ctl.into_iter().map(|c| (c, false)).collect();
        controls.extend((0..lanes.len()).filter(|k| m & (1 << k) != 0).map(|k| (lanes[k], false)));
        super::mask::mc_xor(b, &controls, target, &[], &dirty);
    }
}

/// Value literals of frame `frame` for an r-lane page: lane 0 the constant (`g0` for G, 1 for F); lanes at or
/// above kv are the sign extension of lane kv - 1 (the stored values are kv-lane signed numbers).
fn lq_value_lits_r(w: &PWalk, sch: &PSched, frame: usize, g0: bool, g1: Option<bool>, r: usize) -> (Vec<PL>, Vec<PL>) {
    let kv = sch.kv[frame];
    assert!(kv >= 3 && sch.c[frame] >= 3);
    let lane = |j: usize| j.min(kv - 1);
    let g = std::iter::once(PL::C(g0))
        .chain((1..r).map(|j| match (j, g1) {
            (1, Some(v)) => PL::C(v),
            _ => PL::Q(w.af(frame, lane(j))),
        }))
        .collect();
    let f = std::iter::once(PL::C(true)).chain((1..r).map(|j| PL::Q(w.bf(lane(j))))).collect();
    (g, f)
}

/// U literals of frame `frame` (asig 0..r; lane 0 the constant 0 when sigma is hosted there).
fn lq_u_lits_r(w: &PWalk, sch: &PSched, frame: usize, u0_hosted: bool, r: usize) -> Vec<PL> {
    assert!(sch.kc[frame] >= r);
    (0..r)
        .map(|s| if s == 0 && u0_hosted { PL::C(false) } else { PL::Q(w.asig(frame, s)) })
        .collect()
}

/// mc_xor with the virtual ONE control dropped; `dirty` filtered against the gate's own lanes.
fn lq_mcx(b: &mut B, ctls: &[QubitId], target: QubitId, dirty: &[QubitId]) {
    let lits: Vec<(QubitId, bool)> = ctls.iter().copied().filter(|&q| q != ONE).map(|q| (q, false)).collect();
    let dirty: Vec<QubitId> =
        dirty.iter().copied().filter(|q| *q != target && !lits.iter().any(|l| l.0 == *q)).collect();
    super::mask::mc_xor(b, &lits, target, &[], &dirty);
}

/// t += [AND ctls] a (mod 2^n), a restored: the TTK ripple runs uncontrolled and only its writes into t carry the
/// controls (ctls empty: the plain TTK adder).
fn lq_ttk_add_ctl(b: &mut B, a: &[QubitId], t: &[QubitId], ctls: &[QubitId], dirty: &[QubitId]) {
    let n = t.len();
    assert_eq!(a.len(), n);
    let wr = |b: &mut B, i: usize| {
        let mut c = ctls.to_vec();
        c.push(a[i]);
        lq_mcx(b, &c, t[i], dirty);
    };
    if n == 1 {
        wr(b, 0);
        return;
    }
    for i in 1..n {
        b.cx(a[i], t[i]);
    }
    for i in (1..n - 1).rev() {
        b.cx(a[i], a[i + 1]);
    }
    for i in 0..n - 1 {
        b.ccx(t[i], a[i], a[i + 1]);
    }
    for i in (1..n).rev() {
        wr(b, i);
        b.ccx(t[i - 1], a[i - 1], a[i]);
    }
    for i in 1..n - 1 {
        b.cx(a[i], a[i + 1]);
    }
    wr(b, 0);
    for i in 1..n {
        b.cx(a[i], t[i]);
    }
}

/// q <- q (1 + 2 a) mod 2^m under [AND ctls]; `a` (at least m - 1 lanes) restored.
fn lq_mul_odd(b: &mut B, a: &[QubitId], q: &[QubitId], ctls: &[QubitId], dirty: &[QubitId]) {
    let m = q.len();
    for i in (0..m.saturating_sub(1)).rev() {
        let target = &q[i + 1..];
        let mut c = ctls.to_vec();
        c.push(q[i]);
        lq_ttk_add_ctl(b, &a[..target.len()], target, &c, dirty);
    }
}

/// q += [AND ctls] k (mod 2^m), by multi-controlled increments.
fn lq_add_const(b: &mut B, q: &[QubitId], k: u64, ctls: &[QubitId], dirty: &[QubitId]) {
    for j in 0..q.len() {
        if (k >> j) & 1 == 0 {
            continue;
        }
        let word = &q[j..];
        for i in (1..word.len()).rev() {
            let mut c = ctls.to_vec();
            c.extend(&word[..i]);
            lq_mcx(b, &c, word[i], dirty);
        }
        lq_mcx(b, ctls, word[0], dirty);
    }
}

/// ((sp - 1) / 2 mod 2^(r-1)) for rho = 0 and rho = 1.
fn lq_half_consts(r: usize) -> (u64, u64) {
    let m = (1u64 << r) - 1;
    let p = super::frogdrop_sched::p().as_limbs()[0] & m;
    let (s0, s1) = (p, p.wrapping_neg() & m);
    assert!(s0 & 1 == 1 && s1 & 1 == 1);
    ((s0 - 1) >> 1, (s1 - 1) >> 1)
}

/// In place under [AND ctls]: q = U_hi (U = 2 U_hi, U0 = 0, n = r - 1 lanes) becomes V_hi, where
/// V = 2 V_hi + 1 = (G U + sp) F^-1 mod 2^r: X_hi = G U_hi + (sp - 1)/2 and V_hi = (X_hi - F_hi) F^-1 (mod 2^n).
/// `g` = G lanes 1..n-1 and `f` = F lanes 1..n (G, F odd); every other lane is restored.
pub(super) fn lq_codec_hi(b: &mut B, q: &[QubitId], g: &[QubitId], f: &[QubitId], rho: PL, ctls: &[QubitId], dirty: &[QubitId]) {
    let n = q.len();
    assert!(n >= 2 && g.len() >= n - 1 && f.len() >= n);
    let mask = (1u64 << n) - 1;
    let (c0, c1) = lq_half_consts(n + 1);
    lq_mul_odd(b, g, q, ctls, dirty);
    match rho {
        PL::C(v) => lq_add_const(b, q, if v { c1 } else { c0 }, ctls, dirty),
        PL::Q(rq) => {
            lq_add_const(b, q, c0, ctls, dirty);
            let mut c = ctls.to_vec();
            c.push(rq);
            lq_add_const(b, q, c1.wrapping_sub(c0) & mask, &c, dirty);
        }
    }
    for &x in q {
        lq_mcx(b, ctls, x, dirty);
    }
    lq_ttk_add_ctl(b, &f[..n], q, ctls, dirty);
    for &x in q {
        lq_mcx(b, ctls, x, dirty);
    }
    b.begin();
    lq_mul_odd(b, f, q, ctls, dirty);
    let mf = b.end();
    b.play(&mf, true);
}

/// Clean h (n = r - 1 lanes) <- V_hi for an even G (post-step state): V = 2 V_hi + 1 = (G U + sp) F^-1 mod 2^r, so
/// X_hi = (G/2) U + (sp - 1)/2 and V_hi = (X_hi - F_hi) F^-1 (mod 2^n). `gh` = G lanes 1..n, `u` = U lanes
/// 0..n-1, `f` = F lanes 1..n; every other lane is restored. Undo by playing it reversed.
///
/// With `g1_one`, G' = 2 (mod 4) and `gh` = G lanes 2..n: (G/2) U = U + 2 (G/4) U.
#[allow(clippy::too_many_arguments)]
pub(super) fn lq_oracle_even(b: &mut B, h: &[QubitId], gh: &[QubitId], u: &[QubitId], f: &[QubitId], rho: PL, dirty: &[QubitId], g1_one: bool) {
    let n = h.len();
    assert!(n >= 2 && gh.len() + usize::from(g1_one) >= n && u.len() >= n && f.len() >= n);
    let (c0, c1) = lq_half_consts(n + 1);
    for j in 0..n {
        let (b0, b1) = ((c0 >> j) & 1 == 1, (c1 >> j) & 1 == 1);
        match rho {
            PL::C(v) => {
                if if v { b1 } else { b0 } {
                    b.x(h[j]);
                }
            }
            PL::Q(rq) => {
                if b0 {
                    b.x(h[j]);
                }
                if b0 != b1 {
                    b.cx(rq, h[j]);
                }
            }
        }
    }
    if g1_one {
        lq_ttk_add_ctl(b, &u[..n], h, &[], dirty);
        for i in 0..n - 1 {
            let target = &h[i + 1..];
            lq_ttk_add_ctl(b, &gh[..target.len()], target, &[u[i]], dirty);
        }
    } else {
        for i in 0..n {
            let target = &h[i..];
            lq_ttk_add_ctl(b, &gh[..target.len()], target, &[u[i]], dirty);
        }
    }
    for &x in h {
        b.x(x);
    }
    lq_ttk_add_ctl(b, &f[..n], h, &[], dirty);
    for &x in h {
        b.x(x);
    }
    b.begin();
    lq_mul_odd(b, f, h, &[], dirty);
    let mf = b.end();
    b.play(&mf, true);
}

/// Step core of the Q851 inverse walk, after the value add (G' even, U and F unchanged): fill (`clear` = false) or
/// empty (`clear` = true) the clean hosts with V'_hi = V'1..V'4 of frame t.
#[allow(clippy::too_many_arguments)]
fn lq5_step_hosts(b: &mut B, w: &PWalk, sch: &PSched, t: usize, rho: &ParityCtl, hosts: &[QubitId], dirty: &[QubitId], clear: bool) {
    assert_eq!(hosts.len(), LQ_R - 1);
    let r = lq_fold(b, rho);
    if sch.kv[t] >= LQ_R {
        let g_lo = if LQ_G1_HOST { 2 } else { 1 };
        let gh: Vec<QubitId> = (g_lo..LQ_R).map(|j| w.af(t, j)).collect();
        let u: Vec<QubitId> = (0..LQ_R - 1).map(|s| w.asig(t, s)).collect();
        let f: Vec<QubitId> = (1..LQ_R).map(|j| w.bf(j)).collect();
        b.begin();
        lq_oracle_even(b, hosts, &gh, &u, &f, r, dirty, LQ_G1_HOST);
        let o = b.end();
        b.play(&o, clear);
    } else {
        let (g, f) = lq_value_lits_r(w, sch, t, false, LQ_G1_HOST.then_some(true), LQ_R);
        let u = lq_u_lits_r(w, sch, t, false, LQ_R);
        for bit in 1..LQ_R {
            lq_vr_xor(b, LQ_R, LqKind::V, bit, &g, &f, &u, r, None, hosts[bit - 1], dirty);
        }
    }
    lq_unfold(b, rho);
}

/// Cofactor sign-copy range handled by lsc around the paged role swap: none on the frames whose whole V is paged
/// (their sign copies are exchanged directly by lq_swap_sign_copies).
fn lq_swap_lsc(sch: &PSched, frame: usize) -> (usize, usize) {
    if sch.kc[frame] <= PAGE_INV { (sch.w, sch.w) } else { (0, PAGE_INV) }
}

/// On the frames whose whole V is paged, the cofactor sign copies of both rings hold the old signs U_top, V_top:
/// exchanging them under sigma gives the new signs (the in-place page swap sets the U top lane to V_top).
fn lq_swap_sign_copies(b: &mut B, w: &PWalk, sch: &PSched, frame: usize, sg: QubitId) {
    let kc = sch.kc[frame];
    if kc <= PAGE_INV {
        for s in kc..sch.w - sch.c[frame] {
            b.cswap(sg, w.asig(frame, s), w.bsig(s));
        }
    }
}

/// Role swap of the paged low lanes (pre-swap state of frame `frame`, U0 = 0 under the hosted sigma), in place:
/// U_hi <- sg ? V_hi : U_hi. The new V low lanes are the old U lanes, which the post-swap identity gives back.
fn lq5_swap_low(b: &mut B, w: &PWalk, sch: &PSched, frame: usize, sg: QubitId, rho: &ParityCtl, dirty: &[QubitId]) {
    let r = lq_fold(b, rho);
    let q: Vec<QubitId> = (1..LQ_R).map(|s| w.asig(frame, s)).collect();
    if sch.kv[frame] >= LQ_R {
        let g: Vec<QubitId> = (1..LQ_R - 1).map(|j| w.af(frame, j)).collect();
        let f: Vec<QubitId> = (1..LQ_R).map(|j| w.bf(j)).collect();
        lq_codec_hi(b, &q, &g, &f, r, &[sg], dirty);
    } else {
        // D_k = V_k ^ U_k depends on U_0..U_{k-1} only: toggle from the top lane down.
        let (g, f) = lq_value_lits_r(w, sch, frame, true, None, LQ_R);
        let u = lq_u_lits_r(w, sch, frame, true, LQ_R);
        for k in (1..LQ_R).rev() {
            let mut uk = u.clone();
            for x in uk.iter_mut().skip(k) {
                *x = PL::C(false);
            }
            lq_vr_xor(b, LQ_R, LqKind::D, k, &g, &f, &uk, r, Some(sg), q[k - 1], dirty);
        }
    }
    lq_unfold(b, rho);
}

/// Eraser reads of the paged V3.. (pre-swap frame `frame`, U0 hosted): targets[k] ^= V(3 + k) ^ rho.
pub(super) fn lq5_eraser_toggle(b: &mut B, w: &PWalk, sch: &PSched, frame: usize, rho: &ParityCtl, targets: &[QubitId], dirty: &[QubitId]) {
    assert_eq!(targets.len(), LQ_R - 3);
    let r = lq_fold(b, rho);
    if sch.kv[frame] >= LQ_R {
        let q: Vec<QubitId> = (1..LQ_R).map(|s| w.asig(frame, s)).collect();
        let g: Vec<QubitId> = (1..LQ_R - 1).map(|j| w.af(frame, j)).collect();
        let f: Vec<QubitId> = (1..LQ_R).map(|j| w.bf(j)).collect();
        b.begin();
        lq_codec_hi(b, &q, &g, &f, r, &[], dirty);
        let cd = b.end();
        b.play(&cd, false);
        for (k, &t) in targets.iter().enumerate() {
            b.cx(q[2 + k], t);
        }
        b.play(&cd, true);
    } else {
        let (g, f) = lq_value_lits_r(w, sch, frame, true, None, LQ_R);
        let u = lq_u_lits_r(w, sch, frame, true, LQ_R);
        for (k, &t) in targets.iter().enumerate() {
            lq_vr_xor(b, LQ_R, LqKind::V, 3 + k, &g, &f, &u, r, None, t, dirty);
        }
    }
    lq_unfold(b, rho);
    for &t in targets {
        rho.xor_into(b, t);
    }
}

/// bsig(k) ^= V_k of frame `frame` for k = 4..PAGE_INV (G0 = F0 = 1), by the ANF (walk ends).
pub(super) fn lq5_vhigh_xor(b: &mut B, w: &PWalk, sch: &PSched, frame: usize, u0_hosted: bool, rho: &ParityCtl, dirty: &[QubitId]) {
    let (g, f) = lq_value_lits_r(w, sch, frame, true, None, LQ_R);
    let u = lq_u_lits_r(w, sch, frame, u0_hosted, LQ_R);
    let r = lq_fold(b, rho);
    for bit in 4..PAGE_INV {
        lq_vr_xor(b, LQ_R, LqKind::V, bit, &g, &f, &u, r, None, w.bsig(bit), dirty);
    }
    lq_unfold(b, rho);
}

