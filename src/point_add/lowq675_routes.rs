//! The gates are permutations on five gap wires and four arbitrary owners.
//! All raw inputs F/I and active-owner/early-gate care were checked on both B50s.
use super::builder::{B,G};
use crate::circuit::QubitId;
pub fn bounds(col:usize,kmax:usize)->Vec<usize>{
    let raw: &[usize] = CUTS.get(col).copied().unwrap_or(&[0,1,2,3,5,8,13,18,23]);
    let mut result:Vec<_>=raw.iter().copied().filter(|&x|x<kmax).collect();
    result.push(kmax);result
}
pub fn record(b:&mut B,col:usize,lo:isize,hi:isize,sy:&[QubitId],gap:&[QubitId],
              owners:[QubitId;4],flag:QubitId,dirty:&[QubitId])->Vec<G>{
    assert!(sy.len()==8 && gap.len()>=5);
    let mut data=gap[..5].to_vec();data.extend(owners);
    assert!(!data.contains(&flag) && !sy.contains(&flag));
    b.begin();
    for &(c,a,z,size,off,n) in RECORDS {
        if c!=col {continue;}
        let selector:Vec<_>=(0..7).map(|i|(sy[i],(size>>i)&1==0)).collect();
        super::mask::mc_xor(b,&selector,flag,&[],dirty);
        for &(target,ones,mask) in &GATES[off..off+n] {
            let mut controls=vec![(flag,false)];
            controls.extend((0..9).filter(|&i|((mask>>i)&1)!=0).map(|i|(data[i],(ones>>i)&1==0)));
            super::mask::mc_xor(b,&controls,data[target],&[],dirty);
        }
        super::mask::mc_xor(b,&selector,flag,&[],dirty);
    }
    b.end()
}
