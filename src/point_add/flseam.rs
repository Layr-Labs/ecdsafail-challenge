fn mcx(out: &mut Vec<Row>, ctl: &[(u16, bool)], t: u16, dirty: &[u16]) {
    for &(l, p) in ctl { if !p { out.push([6, l, NONE, NONE]); } }
    let c: Vec<u16> = ctl.iter().map(|z| z.0).collect();
    match c.len() {
        0 => out.push([6, t, NONE, NONE]), 1 => out.push([8, c[0], t, NONE]), 2 => out.push([13, c[0], c[1], t]),
        u => { let v: Vec<u16> = dirty.iter().copied().filter(|d| !c.contains(d) && *d != t).take(u - 2).collect(); assert!(v.len() == u - 2, "flseam: dirty lanes");
            let a = [13, c[0], c[1], v[0]]; let m: Vec<Row> = (2..u - 1).map(|j| [13, c[j], v[j - 2], v[j - 1]]).collect(); let z = [13, c[u - 1], v[u - 3], t];
            for _ in 0..2 { out.push(a); out.extend(m.iter()); out.push(z); out.extend(m.iter().rev()); } } }
    for &(l, p) in ctl { if !p { out.push([6, l, NONE, NONE]); } }
}
/// the transcoder's records on an item's lanes
pub fn seam_rows(lanes: &[u16; 11], dirty: &[u16]) -> Vec<Row> {
    let mut o = Vec::new();
    for (t, cs) in SEAM.iter() { let ctl: Vec<(u16, bool)> = cs.iter().map(|&x| (lanes[(x / 2) as usize], x % 2 == 1)).collect(); mcx(&mut o, &ctl, lanes[*t as usize], dirty); }
    assert!(o.len() == 16_429);
    o
}
