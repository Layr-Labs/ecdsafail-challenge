'use strict';
// q648 build entry (hole), from src/point_add/construction:   node q648/point.cjs raw|spans FILE
// Q648_PROFILE selects the stage config of the public-649 generator (Q/point-i.cjs):
//   '649' (default) = stock stage-config.json (the public 649, unchanged, no pins)
//   '649p'          = stock 649 geometry + every landed q648 piece (pins + module overrides, Q/q648-pieces.json) = the q648 base at width 649
//   '648'           = stage-config-648.json (width 648: 7 helpers 512,641..646, sign on 647)
//   'tight-landed'  = 649 geometry, every LANDED stage (q648-pieces.json tight list) on 7 sites at once
//   'tight-<stage>' = stage-config-649t-<stage>.json (width 649; <stage> on 7 sites, physical 647 banned for it)
// Configs are generated by Q/q648-configs.cjs from Q/q648-drops.json. Other env knobs that select configs are cleared.
const path=require('path');const Q=path.join(__dirname,'../research/agents/midpoint-implicit-query-20261109/q651-ten-field');
const P=process.env.Q648_PROFILE||'649';
// clear every Q648_* knob except the profile, then apply the landed pieces' pins (Q/q648-pins.json) unless stock '649'
for(const k of Object.keys(process.env))if(k.startsWith('Q648_')&&k!=='Q648_PROFILE')delete process.env[k];
const PINS=P==='649'?{}:(require(path.join(Q,'q648-pieces.json')).env||{});
Object.assign(process.env,PINS);
const file=P==='649'?'stage-config.json':P==='649p'?'stage-config-649p.json':P==='648'?'stage-config-648.json':P==='tight-landed'?'stage-config-649t-landed.json':/^tight-(upper|multiply|divide|history)$/.test(P)?'stage-config-649t-'+P.slice(6)+'.json':null;
if(!file)throw Error('Q648_PROFILE must be 649, 649p, 648, tight-landed or tight-<upper|multiply|divide|history>');
process.env.TRACK_I_CONFIG=path.join(Q,file);
const {GateWriter}=require(path.join(Q,'point-i.cjs'));
module.exports={GateWriter};
if(require.main===module){const [mode,f]=process.argv.slice(2);if(!['raw','spans'].includes(mode)||!f||require('os').endianness()!=='LE')throw Error('use raw FILE or spans FILE');
 console.error('q648: profile '+P+' config '+file+' pins '+JSON.stringify(PINS));console.log(JSON.stringify(new GateWriter(mode==='raw'?f:null,mode==='spans'?f:undefined).produce(),null,2));}
